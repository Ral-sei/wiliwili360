#!/usr/bin/env python3
"""Generate the embedded Xbox 360 CA bundle C source.

Usage:
    gen_xbox360_ca_bundle.py <cacert.pem> <out.c> [expected-sha256]

The output defines two symbols consumed by
wiliwili/source/platform/xbox360/xbox360_ca.c:

    const unsigned char x360_ca_bundle_pem[];
    const unsigned int  x360_ca_bundle_pem_len;

The trailing NUL byte is part of the array and counted in the length:
mbedtls_x509_crt_parse() only detects PEM input when buf[buflen - 1] == '\0'.
"""

import hashlib
import os
import sys


def fail(message):
    sys.stderr.write("gen_xbox360_ca_bundle: %s\n" % message)
    raise SystemExit(1)


def main(argv):
    if len(argv) < 3 or len(argv) > 4:
        fail("usage: gen_xbox360_ca_bundle.py <cacert.pem> <out.c> [expected-sha256]")

    pem_path, out_path = argv[1], argv[2]
    expected = argv[3].strip().upper() if len(argv) == 4 else ""

    with open(pem_path, "rb") as handle:
        data = handle.read()

    if not data:
        fail("%s is empty" % pem_path)
    if b"-----BEGIN CERTIFICATE-----" not in data:
        fail("%s does not contain any PEM certificate" % pem_path)
    if expected:
        actual = hashlib.sha256(data).hexdigest().upper()
        if actual != expected:
            fail(
                "SHA-256 mismatch for %s\n  expected: %s\n  actual:   %s"
                % (pem_path, expected, actual)
            )

    lines = []
    lines.append("/* Generated by scripts/gen_xbox360_ca_bundle.py. Do not edit. */\n")
    lines.append("/* Source: %s (%d bytes) */\n" % (os.path.basename(pem_path), len(data)))
    lines.append("const unsigned char x360_ca_bundle_pem[] = {\n")
    for offset in range(0, len(data), 16):
        chunk = data[offset:offset + 16]
        lines.append("    " + ",".join("0x%02x" % byte for byte in chunk) + ",\n")
    # mbedtls_x509_crt_parse() requires the buffer to be NUL terminated.
    lines.append("    0x00\n};\n")
    lines.append("const unsigned int x360_ca_bundle_pem_len = %du;\n" % (len(data) + 1))

    with open(out_path, "w", newline="\n") as handle:
        handle.writelines(lines)

    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
